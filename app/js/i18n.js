let lang = 'en';

export function setLang(pref) {
  const ui = (chrome.i18n.getUILanguage() || navigator.language || 'en').slice(0, 2).toLowerCase();
  lang = pref && pref !== 'auto' && STR[pref] ? pref : STR[ui] ? ui : 'en';
  document.documentElement.lang = lang;
}

export function t(key, p) {
  let s = (STR[lang] && STR[lang][key]) ?? STR.en[key] ?? key;
  if (p) for (const [k, v] of Object.entries(p)) s = s.split('{' + k + '}').join(String(v));
  return s;
}
